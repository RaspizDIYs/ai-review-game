const BAGS: Record<Voice, readonly string[]> = {
  sorry: SORRY,
  fixed: FIXED,
  overreach: OVERREACH,
  deny: DENY,
  selfaware: SELFAWARE,
}

/** Сколько всего заготовлено фраз — цифра для README, чтобы не считать руками. */
export const PHRASE_COUNT =
  SORRY.length + FIXED.length + OVERREACH.length + DENY.length + SELFAWARE.length + OWNED.length

function pick(bag: readonly string[], seed: number): string {
  return bag[seed % bag.length]
}

/**
 * Что агент отвечает на обвинение.
 *
 * `seed` — любая строка, отличающая один ответ от другого (id задачи, номер
 * PR, номер попытки). Детерминированность здесь важна: при перерисовке экрана
 * реплика не должна прыгать.
 *
 * Второй мешок голоса подмешивается каждый третий раз — чтобы Оракул не
 * отрицал вину подряд двенадцать ходов, а Дипломат иногда переходил
 * от извинений к самоиронии.
 */
export function replyTo(agent: Agent, seed: string): string {
  const hash = fnv1a(`reply:${agent.slug}:${seed}`)
  const bag = hash % 3 === 2 && agent.voice.length > 1 ? agent.voice[1] : agent.voice[0]
  return pick(BAGS[bag], hash >>> 3)
}

/** Реплика в ответ на `/git-blame`: агента поймали за руку по истории. */
export function ownLine(agent: Agent, seed: string): string {
  return pick(OWNED, fnv1a(`own:${agent.slug}:${seed}`))
}
