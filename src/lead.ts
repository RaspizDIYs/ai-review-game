/**
 * «Веди меня»: экран сам доводит прокрутку до того, ради чего он открылся.
 *
 * Игрок не должен искать, где теперь происходит главное. Отправил ответ,
 * стоя в середине дифа, — и следующий экран открывается там же, а вопрос
 * или кнопка «дальше» остаются ниже сгиба. Листать до них руками каждый
 * раунд — это работа, которой игра не просила.
 *
 * Правило одно и оно скромное: доводим, **только если** цель и правда далеко
 * внизу. Если она и так на виду, дёргать экран незачем — прокрутка без нужды
 * читается как сбой, а не как забота.
 *
 * Живёт в самом экране, а не в общем переключателе экранов: кто рисует
 * главное, тот и знает, где оно.
 */

import { useEffect, useRef } from 'react'

/** Ниже этой доли экрана цель считается «за сгибом». */
const BELOW = 0.6

/** Кадр на отрисовку: до него у только что вставленного экрана нет размеров. */
const SETTLE = 80

export function useLead<T extends HTMLElement>(active = true) {
  const ref = useRef<T>(null)

  useEffect(() => {
    if (!active) return

    const id = setTimeout(() => {
      const el = ref.current
      if (!el) return
      if (el.getBoundingClientRect().top > window.innerHeight * BELOW) {
        // Мгновенно, а не плавно. Плавная прокрутка держится на кадрах
        // анимации: пока экран въезжает — а он въезжает ровно в этот момент —
        // она не стартует вовсе, и доводка молча не происходит. Да и читается
        // мгновенный сдвиг честнее: экран только что сменился целиком.
        el.scrollIntoView({ block: 'start' })
      }
    }, SETTLE)

    return () => clearTimeout(id)
  }, [active])

  return ref
}
